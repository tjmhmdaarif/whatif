"""Assemble the promotional page into a folder that any static host can serve.

The standalone page in ``promo/whatif-promo.html`` is a single file with every
asset inlined, so publishing it is mostly a matter of putting it somewhere a
host will look. This script gathers that page and the social preview image
into one directory, alongside a ``vercel.json`` that sets the cache policy.

    python scripts/publish_promo.py [--out DIR]

Writes ``promo/site/`` by default. Nothing is deployed and nothing is sent
anywhere; the folder is ready for ``vercel deploy`` or any other static host.

Note that this folder sits inside the repository. Vercel refuses a deployment
whose commit author has no permission on the project, and this repository's
author is ``Developer <dev@localhost>``, so ``vercel deploy promo/site`` is
blocked. For Vercel, copy the files to a directory outside the worktree and
deploy from there; this script is for hosts that do not check the commit author.
"""

from __future__ import annotations

import argparse
import json
import shutil
import sys
from pathlib import Path

# A marker file so a re-run knows the directory is ours to clean. Without it the
# script refuses to touch a directory it did not create.
MARKER = ".whatif-promo-site"

# The HTML changes on every build, so it must not be cached hard. The poster
# never changes under the same name, so it can be cached forever.
HTML_CACHE = "no-cache, max-age=0, must-revalidate"
POSTER_CACHE = "public, max-age=31536000, immutable"


def vercel_config() -> dict[str, object]:
    """Return the Vercel configuration for the published folder.

    There are no rewrites: this is one static page, and a rewrite would hide
    the poster from its own path.
    """
    return {
        "cleanUrls": True,
        "headers": [
            {
                "source": "/(.*)",
                "headers": [
                    {"key": "X-Content-Type-Options", "value": "nosniff"},
                    {"key": "Referrer-Policy", "value": "no-referrer"},
                ],
            },
            {
                "source": "/",
                "headers": [{"key": "Cache-Control", "value": HTML_CACHE}],
            },
            {
                "source": "/index.html",
                "headers": [{"key": "Cache-Control", "value": HTML_CACHE}],
            },
            {
                "source": "/poster.jpg",
                "headers": [{"key": "Cache-Control", "value": POSTER_CACHE}],
            },
        ],
    }


def prepare_output(out: Path) -> None:
    """Create the output directory, clearing it if we created it before.

    Raises:
        SystemExit: If the directory exists but was not created by this script.
    """
    if not out.exists():
        out.mkdir(parents=True)
        return

    if not out.is_dir():
        print(f"The output path is not a directory: {out}", file=sys.stderr)
        raise SystemExit(1)

    if not (out / MARKER).exists():
        print(
            f"{out} exists but was not created by this script.\n"
            "It has no marker file, so it is left alone. Choose another --out "
            "directory, or remove this one yourself.",
            file=sys.stderr,
        )
        raise SystemExit(1)

    # A previous run may have left files behind. Clear them so the folder only
    # ever contains what this script writes.
    for child in out.iterdir():
        if child.is_dir() and not child.is_symlink():
            shutil.rmtree(child)
        else:
            child.unlink()

    (out / MARKER).write_text("This folder is generated by scripts/publish_promo.py\n",
                               encoding="utf-8")


def publish(root: Path, out: Path) -> int:
    """Copy the promo assets into the output directory.

    Returns:
        The total size of the published files, in bytes.
    """
    page = root / "promo" / "whatif-promo.html"
    poster = root / "promo" / "poster.jpg"

    if not page.exists():
        print(
            f"No built page at {page}.\n"
            "Build it first:  python scripts/build_promo.py",
            file=sys.stderr,
        )
        return 1

    if not poster.exists():
        print(f"No poster at {poster}.", file=sys.stderr)
        return 1

    demo = root / "promo" / "demo"
    if not (demo / "index.html").exists():
        print(
            f"No built demo at {demo}.\n"
            "Build it first:  python scripts/build_demo.py\n"
            "Without it the page's two 'Try the prototype' buttons 404.",
            file=sys.stderr,
        )
        return 1

    prepare_output(out)

    # A copy, not a transformation: the built page is already self-contained.
    shutil.copyfile(page, out / "index.html")
    shutil.copyfile(poster, out / "poster.jpg")
    # The demo folder ships beside it, because that is where the page links.
    shutil.copytree(demo, out / "demo", dirs_exist_ok=True)
    (out / "vercel.json").write_text(
        json.dumps(vercel_config(), indent=2) + "\n", encoding="utf-8"
    )

    total = 0
    print(f"Publishing to {out}")
    published = [out / "index.html", out / "poster.jpg", out / "vercel.json"]
    published += sorted(path for path in (out / "demo").iterdir() if path.is_file())
    for path in published:
        size = path.stat().st_size
        total += size
        print(f"  {path.relative_to(out)!s:<24} {size // 1024:>5} KB")
    print(f"  {'total':<24} {total // 1024:>5} KB")

    return total


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Assemble the WhatIf promo page into a folder to deploy."
    )
    parser.add_argument(
        "--out",
        default="promo/site",
        help="Output directory (default: promo/site)",
    )
    args = parser.parse_args()

    root = Path(__file__).resolve().parent.parent
    out = Path(args.out)
    if not out.is_absolute():
        out = root / out

    if publish(root, out) == 1:
        return 1

    print()
    print("Deploy it with:")
    print(f"  vercel deploy {out} --prod")
    return 0


if __name__ == "__main__":
    sys.exit(main())
